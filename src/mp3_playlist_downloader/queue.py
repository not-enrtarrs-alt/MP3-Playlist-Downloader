"""Sequential download queue persisted in the videos table."""

from __future__ import annotations

import logging
import sqlite3
import time
from dataclasses import dataclass
from datetime import datetime, timedelta, timezone
from pathlib import Path
from typing import Callable

from . import db, library, paths
from .settings import Settings
from .youtube.download import DownloadCancelled, download_video
from .youtube.errors import AudioConversionError, NetworkError, RateLimitedError, UnavailableError, YouTubeError

logger = logging.getLogger(__name__)


@dataclass
class QueueSummary:
    downloaded: int = 0
    failed: int = 0
    unavailable: int = 0
    cancelled: bool = False
    rate_limited_until: str | None = None


MAX_AUTO_RETRIES = 3


@dataclass(frozen=True)
class PauseState:
    reason: str
    until: str
    streak: int

    @property
    def auto_retry_allowed(self) -> bool:
        """The first rate limit precedes the three allowed automatic retries."""
        return self.reason == "rate_limited" and 1 <= self.streak <= MAX_AUTO_RETRIES


def enqueue_missing(connection: sqlite3.Connection, playlist_id: int, settings: Settings,
                    *, include_existing: bool = False) -> int:
    """Queue eligible rows; include_existing requires prior UI confirmation."""
    if not paths.find_tool("ffmpeg", settings.ffmpeg_path):
        raise YouTubeError("ffmpeg not found. Install it or set its path in Settings → Tools.")
    with connection:
        cursor = connection.execute("""
            UPDATE videos SET download_state='queued',updated_at=?
            WHERE playlist_id=? AND in_playlist=1 AND unavailable=0 AND (downloaded=0 OR ?=1)
              AND download_state NOT IN ('downloading','queued')
        """, (db.utc_now(), playlist_id, int(include_existing)))
    return cursor.rowcount


def existing_count(connection: sqlite3.Connection, playlist_id: int) -> int:
    return int(connection.execute("SELECT COUNT(*) FROM videos WHERE playlist_id=? AND in_playlist=1 AND unavailable=0 AND downloaded=1 AND download_state<>'downloading'", (playlist_id,)).fetchone()[0])


def enqueue_video(connection: sqlite3.Connection, video_id: int, settings: Settings) -> bool:
    """Queue an explicitly confirmed re-download and reset its failure count."""
    if not paths.find_tool("ffmpeg", settings.ffmpeg_path):
        raise YouTubeError("ffmpeg not found. Install it or set its path in Settings → Tools.")
    with connection:
        cursor = connection.execute("""
            UPDATE videos SET download_state='queued',attempts=0,error_kind=NULL,last_error=NULL,updated_at=?
            WHERE id=? AND in_playlist=1 AND unavailable=0 AND download_state<>'downloading'
        """, (db.utc_now(), video_id))
    return bool(cursor.rowcount)


def pending_count(connection: sqlite3.Connection) -> int:
    return int(connection.execute("SELECT COUNT(*) FROM videos WHERE download_state=?", ("queued",)).fetchone()[0])


def recover_interrupted(connection: sqlite3.Connection) -> int:
    """Recover interrupted rows; only clean names generated by this application."""
    import re
    temporary = re.compile(r"^\.tmp-[0-9a-f]{32}\..+", re.IGNORECASE)
    with connection:
        cursor = connection.execute("UPDATE videos SET download_state='queued',updated_at=? WHERE download_state='downloading'", (db.utc_now(),))
    for row in connection.execute("SELECT folder_path FROM playlists"):
        folder = Path(row["folder_path"])
        try:
            for item in folder.iterdir():
                if temporary.match(item.name) and item.is_file() and not item.is_symlink():
                    try:
                        item.unlink()
                    except OSError:
                        logger.warning("Could not clean a stale temporary download.")
        except FileNotFoundError:
            pass
        except OSError:
            logger.warning("Could not scan a playlist folder for stale temporary downloads.")
    return cursor.rowcount


def _set_meta(connection: sqlite3.Connection, key: str, value: str) -> None:
    connection.execute("INSERT INTO meta(key,value) VALUES (?,?) ON CONFLICT(key) DO UPDATE SET value=excluded.value", (key, value))


def pause_state(connection: sqlite3.Connection) -> PauseState:
    values = dict(connection.execute("SELECT key,value FROM meta WHERE key IN ('queue_paused_until','queue_pause_reason','queue_rate_limit_streak')"))
    try:
        streak = max(0, int(values.get("queue_rate_limit_streak", "0")))
    except ValueError:
        streak = 0
    return PauseState(values.get("queue_pause_reason", ""), values.get("queue_paused_until", ""), streak)


def clear_pause(connection: sqlite3.Connection, *, manual: bool) -> None:
    """Clear a pause; only a manual resume resets the rate-limit streak."""
    with connection:
        _set_meta(connection, "queue_paused_until", "")
        _set_meta(connection, "queue_pause_reason", "")
        if manual:
            _set_meta(connection, "queue_rate_limit_streak", "0")


def run_queue(connection: sqlite3.Connection, settings: Settings, *,
              cancelled: Callable[[], bool] = lambda: False,
              progress: Callable[[float, float | None, int | None], None] | None = None,
              started: Callable[[int, str], None] | None = None,
              finished: Callable[[int, bool, str], None] | None = None,
              download: Callable = download_video, wait: Callable[[float], None] = time.sleep,
              clock: Callable[[], datetime] | None = None) -> QueueSummary:
    """Drain queued rows one at a time, persisting every transition."""
    summary = QueueSummary()
    logger.info("Download queue started")
    with connection:
        connection.execute("UPDATE videos SET download_state='idle',updated_at=? WHERE download_state='queued' AND (in_playlist=0 OR unavailable=1)", (db.utc_now(),))
    while not cancelled():
        row = connection.execute("""
            SELECT v.*,p.title AS playlist_title,p.folder_path FROM videos v
            JOIN playlists p ON p.id=v.playlist_id WHERE v.download_state='queued'
            ORDER BY v.playlist_id,v.position,v.id LIMIT 1
        """).fetchone()
        if row is None:
            break
        video = dict(row)
        vid = video["id"]
        with connection:
            connection.execute("UPDATE videos SET download_state='downloading',updated_at=? WHERE id=?", (db.utc_now(), vid))
        if started:
            started(vid, video["title"])
        used = [item[0] for item in connection.execute("SELECT file_path FROM videos WHERE playlist_id=? AND file_path IS NOT NULL UNION SELECT file_path FROM extra_files WHERE playlist_id=?", (video["playlist_id"], video["playlist_id"]))]
        try:
            if video["downloaded"] and video["file_path"]:
                target = library.normalized_path(video["file_path"])
                others = connection.execute("SELECT file_path FROM videos WHERE id<>? AND file_path IS NOT NULL", (vid,)).fetchall()
                if any(library.normalized_path(other["file_path"]) == target for other in others):
                    raise YouTubeError("A tracked file is shared by another video; it cannot be replaced safely.")
            for attempt in range(2):
                try:
                    result = download(video, video["playlist_title"], Path(video["folder_path"]), settings, used_paths=used, progress=progress, cancelled=cancelled, overwrite=bool(video["downloaded"]))
                    break
                except NetworkError:
                    if attempt:
                        raise
                    wait(5)
                    if cancelled():
                        raise DownloadCancelled()
            with connection:
                connection.execute("""
                    UPDATE videos SET downloaded=1,equalized=?,file_path=?,file_size=?,download_state='idle',
                        attempts=0,error_kind=?,last_error=?,updated_at=? WHERE id=?
                """, (int(result.equalized), str(result.file_path), result.file_size, result.warning_kind, result.warning, db.utc_now(), vid))
                _set_meta(connection, "queue_rate_limit_streak", "0")
                _set_meta(connection, "queue_paused_until", "")
                _set_meta(connection, "queue_pause_reason", "")
            summary.downloaded += 1
            logger.info("Downloaded track row %s", vid)
            if finished:
                finished(vid, True, result.warning or "")
        except DownloadCancelled:
            with connection:
                connection.execute("UPDATE videos SET download_state='queued',updated_at=? WHERE id=?", (db.utc_now(), vid))
            summary.cancelled = True
            break
        except RateLimitedError:
            until = ((clock or (lambda: datetime.now(timezone.utc)))() + timedelta(minutes=settings.rate_limit_cooldown_minutes)).isoformat()
            with connection:
                connection.execute("UPDATE videos SET download_state='queued',updated_at=? WHERE id=?", (db.utc_now(), vid))
                streak = pause_state(connection).streak
                _set_meta(connection, "queue_rate_limit_streak", str(streak + 1))
                _set_meta(connection, "queue_paused_until", until)
                _set_meta(connection, "queue_pause_reason", "rate_limited")
            summary.rate_limited_until = until
            logger.warning("Queue paused due to rate limiting")
            break
        except UnavailableError:
            with connection:
                connection.execute("UPDATE videos SET unavailable=1,download_state='idle',error_kind='unavailable',last_error=?,updated_at=? WHERE id=?", ("Video unavailable.", db.utc_now(), vid))
            summary.unavailable += 1
            logger.info("Track row %s unavailable", vid)
            if finished:
                finished(vid, False, "Video unavailable.")
        except Exception as error:
            kind = "network" if isinstance(error, NetworkError) else "other"
            if kind == "network":
                message = "Network error; retry later."
            elif isinstance(error, AudioConversionError):
                message = "Audio conversion failed. Check ffmpeg and ffprobe in Settings → Tools."
            else:
                message = "Download failed; retry later."
            with connection:
                connection.execute("UPDATE videos SET download_state='failed',attempts=attempts+1,error_kind=?,last_error=?,updated_at=? WHERE id=?", (kind, message, db.utc_now(), vid))
            summary.failed += 1
            logger.warning("Track row %s failed (%s)", vid, kind)
            if finished:
                finished(vid, False, message)
    if cancelled():
        summary.cancelled = True
    logger.info("Download queue stopped: %s succeeded, %s failed, %s unavailable", summary.downloaded, summary.failed, summary.unavailable)
    return summary
